/// The lookup text for a medicine: its name plus strength, so a product such
/// as "Dolo 650" is identified rather than just "Dolo".
String medicineLookupName(Medication m) {
  final String? s = m.strengthLabel;
  return s == null ? m.name : '${m.name} ${s.replaceAll(' ', '')}';
}

const String _aiNotice =
    'Generated by AI from general medical knowledge for medicines sold in '
    'India. It can contain mistakes, so confirm with your pharmacist or '
    'doctor before acting on it.';

// -------------------------------------------------------------------- info

class MedicineInfoTab extends ConsumerWidget {
  const MedicineInfoTab({super.key, required this.medication});

  final Medication medication;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final AsyncValue<MedicineProfile> profile =
        ref.watch(medicineProfileProvider(medicineLookupName(medication)));

    return profile.when(
      loading: () => const _Loading(label: 'Reading about this medicine…'),
      error: (_, __) => _Unavailable(
        onRetry: () => ref.invalidate(
          medicineProfileProvider(medicineLookupName(medication)),
        ),
      ),
      data: (MedicineProfile p) => !p.recognized
          ? _Unavailable(
              onRetry: () => ref.invalidate(
                medicineProfileProvider(medicineLookupName(medication)),
              ),
            )
          : _InfoBody(profile: p),
    );
  }
}

class _InfoBody extends StatelessWidget {
  const _InfoBody({required this.profile});

  final MedicineProfile profile;

  @override
  Widget build(BuildContext context) {
    final ThemeData theme = Theme.of(context);
    final AppStatusColors status = context.statusColors;
    final MedicineProfile p = profile;

    Widget bullets(List<String> items) => Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: <Widget>[
            for (final String s in items)
              Padding(
                padding: const EdgeInsets.only(bottom: 6),
                child: Row(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: <Widget>[
                    const Padding(
                      padding: EdgeInsets.only(top: 7, right: 10),
                      child: Icon(Icons.circle, size: 5),
                    ),
                    Expanded(
                      child: Text(s, style: theme.textTheme.bodyMedium),
                    ),
                  ],
                ),
              ),
          ],
        );

    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: <Widget>[
        const InfoBanner(message: _aiNotice, icon: Icons.auto_awesome_outlined),
        if (p.confidence == 'low') ...<Widget>[
          const SizedBox(height: AppSpacing.md),
          const InfoBanner(
            message: 'The assistant was not very sure about this medicine. '
                'Check the details on the packet.',
            tone: AppInfoTone.warning,
            icon: Icons.help_outline_rounded,
          ),
        ],
        if (p.typicalUse != null) ...<Widget>[
          const SectionHeader(title: 'What it is used for'),
          AppCard(child: Text(p.typicalUse!, style: theme.textTheme.bodyMedium)),
        ],
        if (p.ingredients.isNotEmpty || p.genericName != null) ...<Widget>[
          const SectionHeader(title: 'Active ingredient'),
          AppCard(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: <Widget>[
                if (p.ingredients.isEmpty)
                  Text(p.genericName!, style: theme.textTheme.titleSmall)
                else
                  for (final Ingredient i in p.ingredients)
                    Padding(
                      padding: const EdgeInsets.only(bottom: 4),
                      child: Text(i.label, style: theme.textTheme.titleSmall),
                    ),
                if (p.prescriptionStatus != null) ...<Widget>[
                  const SizedBox(height: AppSpacing.sm),
                  Text(
                    p.prescriptionStatus == 'OTC'
                        ? 'Sold over the counter in India'
                        : 'Needs a prescription in India',
                    style: theme.textTheme.bodySmall,
                  ),
                ],
              ],
            ),
          ),
        ],
        if (p.howItWorks != null) ...<Widget>[
          const SectionHeader(title: 'How it works'),
          AppCard(child: Text(p.howItWorks!, style: theme.textTheme.bodyMedium)),
        ],
        if (p.sideEffects.isNotEmpty) ...<Widget>[
          const SectionHeader(title: 'Common side effects'),
          AppCard(child: bullets(p.sideEffects)),
        ],
        if (p.warnings.isNotEmpty) ...<Widget>[
          const SectionHeader(title: 'Be careful if'),
          AppCard(
            color: status.warningContainer,
            borderColor: Colors.transparent,
            child: bullets(p.warnings),
          ),
        ],
        if (p.storage != null) ...<Widget>[
          const SectionHeader(title: 'Storage'),
          AppCard(child: Text(p.storage!, style: theme.textTheme.bodyMedium)),
        ],
      ],
    );
  }
}

// ------------------------------------------------------------ alternatives

class MedicineAlternativesTab extends ConsumerWidget {
  const MedicineAlternativesTab({super.key, required this.medication});

  final Medication medication;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final AsyncValue<MedicineProfile> profile =
        ref.watch(medicineProfileProvider(medicineLookupName(medication)));

    return profile.when(
      loading: () =>
          const _Loading(label: 'Finding brands sold in India…'),
      error: (_, __) => _Unavailable(
        onRetry: () => ref.invalidate(
          medicineProfileProvider(medicineLookupName(medication)),
        ),
      ),
      data: (MedicineProfile p) {
        if (!p.recognized) {
          return _Unavailable(
            onRetry: () => ref.invalidate(
              medicineProfileProvider(medicineLookupName(medication)),
            ),
          );
        }
        final ThemeData theme = Theme.of(context);
        return Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: <Widget>[
            const InfoBanner(
              message: 'Other brands sold in India with the same or a similar '
                  'composition. AI-generated and can contain mistakes. Check '
                  'with your pharmacist or doctor before switching brands.',
              tone: AppInfoTone.warning,
              icon: Icons.medical_information_outlined,
            ),
            const SizedBox(height: AppSpacing.lg),
            if (p.alternatives.isEmpty)
              const EmptyState(
                icon: Icons.swap_horiz_rounded,
                title: 'No alternatives found',
                message: 'Ask your pharmacist about other brands of '
                    'this medicine.',
              )
            else ...<Widget>[
              Text(
                'Your medicine: ${p.ingredients.isNotEmpty ? p.ingredients.map((Ingredient i) => i.label).join(' + ') : (p.genericName ?? p.name)}',
                style: theme.textTheme.titleSmall,
              ),
              const SizedBox(height: AppSpacing.md),
              for (final IndianAlternative a in p.alternatives)
                Padding(
                  padding: const EdgeInsets.only(bottom: AppSpacing.md),
                  child: _AlternativeCard(alternative: a),
                ),
            ],
          ],
        );
      },
    );
  }
}

class _AlternativeCard extends StatelessWidget {
  const _AlternativeCard({required this.alternative});

  final IndianAlternative alternative;

  @override
  Widget build(BuildContext context) {
    final ThemeData theme = Theme.of(context);
    final AppStatusColors status = context.statusColors;
    final bool same = alternative.match == AlternativeMatch.same;
    return AppCard(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: <Widget>[
          Row(
            children: <Widget>[
              Expanded(
                child: Text(alternative.brand, style: theme.textTheme.titleMedium),
              ),
              StatusChip(
                label: same ? 'Same composition' : 'Similar',
                color: same ? status.taken : status.warning,
                containerColor:
                    same ? status.takenContainer : status.warningContainer,
                icon: same ? Icons.check_rounded : Icons.compare_arrows_rounded,
              ),
            ],
          ),
          if (alternative.manufacturer != null)
            Text(alternative.manufacturer!, style: theme.textTheme.bodySmall),
          if (alternative.composition.isNotEmpty) ...<Widget>[
            const SizedBox(height: AppSpacing.sm),
            Text(alternative.composition, style: theme.textTheme.bodyMedium),
          ],
          if (alternative.note != null) ...<Widget>[
            const SizedBox(height: AppSpacing.xs),
            Text(alternative.note!, style: theme.textTheme.bodySmall),
          ],
        ],
      ),
    );
  }
}

// ------------------------------------------------------------------ shared

class _Loading extends StatelessWidget {
  const _Loading({required this.label});
  final String label;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: AppSpacing.huge),
      child: Column(
        children: <Widget>[
          const CircularProgressIndicator(),
          const SizedBox(height: AppSpacing.lg),
          Text(label, style: Theme.of(context).textTheme.bodyMedium),
        ],
      ),
    );
  }
}

class _Unavailable extends StatelessWidget {
  const _Unavailable({required this.onRetry});
  final VoidCallback onRetry;

  @override
  Widget build(BuildContext context) {
    return EmptyState(
      icon: Icons.cloud_off_outlined,
      title: 'No information yet',
      message: 'Medzee could not identify this medicine or reach the '
          'assistant. Check your connection and try again.',
      action: OutlinedButton(onPressed: onRetry, child: const Text('Try again')),
    );
  }
}
